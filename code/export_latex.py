"""Write the data, results and figures used by the LaTeX report and presentation.

Called by `python main.py --export-latex`. Everything lands in
latex/shared/generated/ (tables and \\newcommand macros) and
latex/shared/figures/ (PDF figures), so the documents always show exactly
what the code computed. Never edit those files by hand: re-run the export.
"""
from pathlib import Path

from plots import plot_graph, plot_route, plot_steps

SHARED = Path(__file__).resolve().parent.parent / "latex" / "shared"
GENERATED = SHARED / "generated"
FIGURES = SHARED / "figures"

HEADER = "% AUTO-GENERATED by code/main.py --export-latex. Do not edit; re-run the export instead.\n"


def write(name, body):
    (GENERATED / name).write_text(HEADER + body, encoding="utf-8")


def route_text(route):
    return " $\\to$ ".join(f"V{v}" for v in route)


def cycle_text(tour):
    return "--\\allowbreak ".join(f"V{v}" for v in tour + tour[:1]) if len(tour) > 1 else f"V{tour[0]}"


def edge_text(e, dist):
    return f"V{e[0]}--V{e[1]} ({dist[e[0]][e[1]]:.2f})"


def macros(locations, dist, result, args, checks, recomputed, opt_route, optimum, stats):
    gap = 100 * (result.total - optimum) / optimum
    best_gap = 100 * (stats["best"]["mean"] - optimum) / optimum
    bridge_gap = 100 * (stats["bridge"]["mean"] - optimum) / optimum
    values = {
        "NumVertices": len(dist),
        "NumEdges": len(dist) * (len(dist) - 1) // 2,
        "StartName": next(loc["name"] for loc in locations if loc["role"] == "start"),
        "DCSeed": args.seed,
        "DCRule": args.rule,
        "DCRoute": route_text(result.route),
        "DCTotal": f"{result.total:.2f}",
        "DCRecomputed": f"{recomputed:.2f}",
        "DCAllChecks": "passed" if all(checks.values()) else "FAILED",
        "OptRoute": route_text(opt_route),
        "OptTotal": f"{optimum:.2f}",
        "DCGap": f"{gap:.2f}",
        "RunCount": args.runs,
        "BridgeMean": f"{stats['bridge']['mean']:.2f}",
        "BridgeBest": f"{stats['bridge']['best']:.2f}",
        "BridgeWorst": f"{stats['bridge']['worst']:.2f}",
        "BridgeMeanGap": f"{bridge_gap:.2f}",
        "BridgeOptHits": stats["bridge"]["optimal_hits"],
        "BestRuleOptHits": stats["best"]["optimal_hits"],
        "BestRuleMean": f"{stats['best']['mean']:.2f}",
        "BestRuleBest": f"{stats['best']['best']:.2f}",
        "BestRuleWorst": f"{stats['best']['worst']:.2f}",
        "BestRuleMeanGap": f"{best_gap:.2f}",
    }
    return "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in values.items())


def vertices_table(locations):
    rows = "".join(
        f"{loc['label']} & {loc['name']}{' (start)' if loc['role'] == 'start' else ''} & {loc['area']} & "
        f"{float(loc['lat']):.5f} & {float(loc['lon']):.5f} \\\\\n" for loc in locations)
    return ("\\begin{tabular}{l l l r r}\n\\toprule\n"
            "\\textbf{Vertex} & \\textbf{Location} & \\textbf{Area} & \\textbf{Latitude} & \\textbf{Longitude} \\\\\n"
            f"\\midrule\n{rows}\\bottomrule\n\\end{{tabular}}\n")


def matrix_table(dist):
    n = len(dist)
    head = " & ".join(f"\\textbf{{V{j}}}" for j in range(n))
    rows = "".join(f"\\textbf{{V{i}}} & " + " & ".join(
        "--" if i == j else f"{dist[i][j]:.2f}" for j in range(n)) + " \\\\\n" for i in range(n))
    return (f"\\begin{{tabular}}{{l {'r' * n}}}\n\\toprule\n & {head} \\\\\n"
            f"\\midrule\n{rows}\\bottomrule\n\\end{{tabular}}\n")


def trace_table(result, dist):
    rows = []
    merges = [ev for ev in result.trace if ev["step"] == "merge"]
    for k, ev in enumerate(merges, 1):
        removed = ", ".join(edge_text(e, dist) for e in ev["removed"]) or "--"
        rows.append(
            f"M{k} & {cycle_text(ev['left_tour'])} ({ev['left_cost']:.2f}) & "
            f"{cycle_text(ev['right_tour'])} ({ev['right_cost']:.2f}) & "
            f"{edge_text(ev['bridge'], dist) if ev['bridge'] else '--'} & {removed} & "
            f"{', '.join(edge_text(e, dist) for e in ev['added'])} & {ev['delta']:+.2f} & {ev['cost']:.2f} \\\\\n")
    col = ">{\\raggedright\\arraybackslash}p"
    return (f"\\begin{{tabular}}{{c {col}{{2.6cm}} {col}{{2.6cm}} {col}{{1.9cm}} {col}{{2.45cm}} "
            f"{col}{{2.45cm}} r r}}\n\\toprule\n"
            "\\textbf{Step} & \\textbf{Left tour (km)} & \\textbf{Right tour (km)} & "
            "\\textbf{Shortest bridge} & \\textbf{Edges removed} & \\textbf{Edges added} & "
            "$\\boldsymbol{\\Delta}$ & \\textbf{Merged} \\\\\n"
            f"\\midrule\n{''.join(rows)}\\bottomrule\n\\end{{tabular}}\n")


def divide_tree(result):
    """TikZ tree of the recursive splits; leaves are the base-case sub-tours."""
    splits = {frozenset(ev["cities"]): ev for ev in result.trace if ev["step"] == "split"}
    bases = {frozenset(ev["cities"]): ev for ev in result.trace if ev["step"] == "base"}
    root = next(ev for ev in result.trace if ev["step"] == "split")

    def label(vertices):
        return "\\{" + ",".join(f"V{v}" for v in sorted(vertices)) + "\\}"

    def node(vertices, indent):
        pad = "  " * indent
        key = frozenset(vertices)
        if key in bases:
            ev = bases[key]
            return f"{pad}node[leaf] {{{cycle_text(ev['cities'])}\\\\({ev['cost']:.2f} km)}}"
        ev = splits[key]
        axis = "x" if ev["axis"] == "x" else "y"
        return (f"{pad}node[split] {{{label(vertices)}\\\\split by {axis}}}\n"
                f"{pad}child {{\n{node(ev['left'], indent + 1)}\n{pad}}}\n"
                f"{pad}child {{\n{node(ev['right'], indent + 1)}\n{pad}}}")

    body = node(root["cities"], 1).lstrip()
    return ("\\begin{tikzpicture}[\n"
            "  split/.style={draw, rounded corners, fill=blue!6, align=center, font=\\scriptsize},\n"
            "  leaf/.style={draw, rounded corners, fill=green!8, align=center, font=\\scriptsize},\n"
            "  level 1/.style={sibling distance=7.2cm, level distance=1.5cm},\n"
            "  level 2/.style={sibling distance=3.6cm, level distance=1.5cm},\n"
            "  level 3/.style={sibling distance=1.9cm, level distance=1.5cm}]\n"
            f"\\{body};\n\\end{{tikzpicture}}\n")


def worked_merge(result, dist):
    """The final (top-level) merge written out as a hand calculation."""
    ev = next(e for e in reversed(result.trace) if e["step"] == "merge")
    w = lambda e: f"{dist[e[0]][e[1]]:.2f}"  # noqa: E731
    lines = [
        f"The two halves return the sub-tours $T_1 = $ {cycle_text(ev['left_tour'])} "
        f"(length {ev['left_cost']:.2f} km) and $T_2 = $ {cycle_text(ev['right_tour'])} "
        f"(length {ev['right_cost']:.2f} km).",
    ]
    if ev["bridge"]:
        a, b = ev["bridge"]
        lines.append(f"Checking all $|T_1|\\cdot|T_2| = {len(ev['left_tour'])}\\cdot{len(ev['right_tour'])} = "
                     f"{len(ev['left_tour']) * len(ev['right_tour'])}$ cross pairs, the shortest bridge is "
                     f"V{a}--V{b} with $w = {w((a, b))}$ km.")
    removed, added = ev["removed"], ev["added"]
    lines.append(
        "Among the ways of opening one edge next to each bridge endpoint and closing the loop, the cheapest "
        f"removes {' and '.join(f'V{u}--V{v}' for u, v in removed)} and adds "
        f"{' and '.join(f'V{u}--V{v}' for u, v in added)}:")
    lines.append(
        "\\[\\Delta = (" + " + ".join(w(e) for e in added) + ") - (" + " + ".join(w(e) for e in removed)
        + f") = {ev['delta']:+.2f}\\text{{ km}},\\]")
    lines.append(
        f"\\[L(T) = L(T_1) + L(T_2) + \\Delta = {ev['left_cost']:.2f} + {ev['right_cost']:.2f} "
        f"{'+' if ev['delta'] >= 0 else '-'} {abs(ev['delta']):.2f} = {ev['cost']:.2f}\\text{{ km}}.\\]")
    lines.append(f"The merged cycle is {cycle_text(ev['tour'])}, which visits all {len(ev['tour'])} vertices once.")
    return "\n".join(lines) + "\n"


def legs_table(route, locations, dist):
    rows, cumulative = [], 0.0
    for k in range(len(route) - 1):
        u, v = route[k], route[k + 1]
        cumulative += dist[u][v]
        rows.append(f"{k + 1} & V{u} {locations[u]['name']} & V{v} {locations[v]['name']} & "
                    f"{dist[u][v]:.2f} & {cumulative:.2f} \\\\\n")
    return ("\\begin{tabular}{c l l r r}\n\\toprule\n"
            "\\textbf{Leg} & \\textbf{From} & \\textbf{To} & \\textbf{km} & \\textbf{Cumulative} \\\\\n"
            f"\\midrule\n{''.join(rows)}\\midrule\n"
            f"\\multicolumn{{3}}{{r}}{{\\textbf{{Total}}}} & \\multicolumn{{2}}{{r}}{{\\textbf{{{cumulative:.2f} km}}}} \\\\\n"
            "\\bottomrule\n\\end{tabular}\n")


def experiments_table(stats, optimum, runs):
    rows = []
    for rule, name in (("bridge", "Shortest bridge (paper)"), ("best", "Best splice (variant)")):
        s = stats[rule]
        rows.append(f"{name} & {s['best']:.2f} & {s['worst']:.2f} & {s['mean']:.2f} & {s['std']:.2f} & "
                    f"{100 * (s['mean'] - optimum) / optimum:.2f}\\% & {s['optimal_hits']}/{runs} & "
                    f"{s['ms_per_run']:.3f} \\\\\n")
    rows.append(f"Held--Karp (exact) & {optimum:.2f} & {optimum:.2f} & {optimum:.2f} & 0.00 & 0.00\\% & -- & -- \\\\\n")
    return ("\\begin{tabular}{l r r r r r r r}\n\\toprule\n"
            "\\textbf{Method} & \\textbf{Best} & \\textbf{Worst} & \\textbf{Mean} & \\textbf{Std.} & "
            "\\textbf{Mean gap} & \\textbf{Optimal} & \\textbf{ms/run} \\\\\n"
            f"\\midrule\n{''.join(rows)}\\bottomrule\n\\end{{tabular}}\n")


def export(locations, coords, dist, result, args, checks, recomputed, opt_route, optimum, stats):
    GENERATED.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)

    write("macros.tex", macros(locations, dist, result, args, checks, recomputed, opt_route, optimum, stats))
    write("vertices.tex", vertices_table(locations))
    write("matrix.tex", matrix_table(dist))
    write("trace.tex", trace_table(result, dist))
    write("divide-tree.tex", divide_tree(result))
    write("worked-merge.tex", worked_merge(result, dist))
    write("legs.tex", legs_table(result.route, locations, dist))
    write("experiments.tex", experiments_table(stats, optimum, args.runs))

    tmp = FIGURES / "_tmp.png"
    plot_graph(locations, coords, dist, tmp, FIGURES / "graph.pdf")
    plot_steps(coords, result, tmp, FIGURES / "steps.pdf")
    plot_route(locations, coords, result.route, result.total, tmp, FIGURES / "route.pdf")
    tmp.unlink()

    print(f"LaTeX tables written to {GENERATED}")
    print(f"LaTeX figures written to {FIGURES}")
